// مفتاح تشفير electron-store (يحمي ملف الترخيص/كلمة السر الإداري/مفتاح
// تشفير النسخ الاحتياطي المحفوظ محلياً).
//
// قبل هذا الملف: كان المفتاح نص ثابت بالكود نفسه — يعني نفس المفتاح بكل نسخة
// مثبّتة بكل الدنيا، وأي شخص يفكّ الـ app.asar (أمر بسيط: `npx asar extract`)
// يقرأه مباشرة ويفك تشفير أي جهاز.
//
// الحل هنا: نشتق المفتاح من Hardware ID الجهاز نفسه + بذرة ثابتة بالكود
// (Pepper). النتيجة: المفتاح يختلف تلقائياً من جهاز لجهاز، فحتى لو أحد قرأ
// الكود المصدري، ما ينفعه إلا وهو فعلياً على نفس الجهاز المستهدف (لأنه يحتاج
// Hardware ID ذاك الجهاز بالضبط ليشتق نفس المفتاح). هذا يرفع العتبة كثير،
// لكن -بصراحة زي أي حماية محلية- ما يعتبر "سر" بالمعنى الأمني الكامل لأنه
// المشتق نفسه (hash) يصير محسوب فعلياً بذاكرة نفس الجهاز وقت التشغيل.
//
// ⚠️ تنبيه مهم: تغيير هذا الملف بعد ما عندك زبائن حقيقيين فعّلوا نسخهم يخلي
// ملفات الترخيص/النسخ الاحتياطي القديمة عندهم يتعذّر فكها (لازم تفعيل جديد،
// النسخ الاحتياطية القديمة المشفّرة تنعزل). ثبّته قبل التسليم الفعلي.

const crypto = require('crypto');
const { machineIdSync } = require('node-machine-id');

const APP_PEPPER = 'raqeem-mtabty-v2-static-pepper-x9Qf3';

let cached = null;

function getLocalStoreKey() {
  if (cached) return cached;
  const hwid = machineIdSync({ original: true });
  cached = crypto.createHash('sha256').update(hwid + APP_PEPPER).digest('hex');
  return cached;
}

module.exports = { getLocalStoreKey };
